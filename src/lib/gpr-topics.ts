function normalizeTopicText(value: string) {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim()
}

function compileTopicRule(rule: TopicRule) {
  // Longest terms first so "supreme court" wins over "court".
  const terms = [...new Set(rule.terms.map(normalizeTopicText))]
    .filter(Boolean)
    .sort((a, b) => b.length - a.length)
  return {
    topic: rule.topic,
    regex: new RegExp(
      `(?<![a-z0-9])(?:${terms.join("|")})(?![a-z0-9])`,
      "g",
    ),
  }
}

const COMPILED = RULES.map(compileTopicRule)

// Returns the area with the most matched terms; ties fall back to the priority
// order above. Headlines with no recognizable term are treated as politics, the
// broadest institutional bucket.
export function classifyTopic(title: string, summary = ""): GprTopic {
  const value = normalizeTopicText(`${title} ${summary}`)
  let best: GprTopic = "politics"
  let bestScore = 0

  for (const rule of COMPILED) {
    const matches = value.match(rule.regex)
    if (!matches) continue
    const score = matches.length
    if (
      score > bestScore ||
      (score === bestScore &&
        gprTopicPriority.indexOf(rule.topic) < gprTopicPriority.indexOf(best))
    ) {
      best = rule.topic
      bestScore = score
    }
  }

  return best
}

// Whether the headline mentions at least one term from any area. Used to keep
// general-interest Google results (sports, celebrities, curiosities) out of the
// country feed unless they really touch politics, economy, finance, law or GPR.
export function hasTopicSignal(title: string, summary = "") {
  const value = normalizeTopicText(`${title} ${summary}`)
  return COMPILED.some((rule) => value.match(rule.regex) !== null)
}
