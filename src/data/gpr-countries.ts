// Lowercase, strip accents and collapse everything else into single spaces.
export function normalizeText(value: string) {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim()
}

const displayNames =
  typeof Intl !== "undefined" && "DisplayNames" in Intl
    ? new Intl.DisplayNames(["es"], { type: "region" })
    : null

export function countryDisplayName(iso2: string, fallback: string) {
  const override = NAME_OVERRIDES[iso2] ?? countryNames[iso2]
  if (override) return override
  if (/^[A-Z]{2}$/.test(iso2)) {
    try {
      const name = displayNames?.of(iso2)
      if (name && name !== iso2) return name
    } catch {
      // Unknown region code: keep the map name.
    }
  }
  return fallback
}

export function iso3Of(iso2: string) {
  return ISO3_BY_ISO2[iso2] ?? iso2.toUpperCase().slice(0, 3)
}

export type CountryEntity = {
  iso2: string
  iso3: string
  name: string
  aliases: string[]
}

export const countryEntities: CountryEntity[] = worldMap.map((country) => {
  const name = countryDisplayName(country.id, country.name)
  return {
    iso2: country.id,
    iso3: iso3Of(country.id),
    name,
    aliases: [country.name, name, ...(ALIASES_BY_ISO2[country.id] ?? [])],
  }
})

export const countryByIso3 = new Map(
  countryEntities.map((country) => [country.iso3, country]),
)

export function entityForIso3(iso3: string) {
  return countryByIso3.get(iso3)
}
