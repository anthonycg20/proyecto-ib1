export const riskLevels = [
  { label: "Bajo", className: "low", max: 20 },
  { label: "Moderado", className: "moderate", max: 40 },
  { label: "Elevado", className: "elevated", max: 60 },
  { label: "Alto", className: "high", max: 80 },
  { label: "Crítico", className: "critical", max: 100 },
]

export function getRiskLevel(score: number | undefined) {
  return score === undefined
    ? { label: "Sin datos", className: "unavailable", max: 100 }
    : riskLevels.find((level) => score <= level.max)!
}
